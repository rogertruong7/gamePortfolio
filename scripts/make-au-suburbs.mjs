// Builds web/api/_lib/auSuburbs.js from GeoNames' Australian postcode list.
// Usage: download https://download.geonames.org/export/zip/AU.zip, unzip it,
// then run: node scripts/make-au-suburbs.mjs path/to/AU.txt
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const PRECISE = "6"; // GeoNames accuracy 6 is the locality itself, not a PO box or postcode centre.
const source = process.argv[2];
if (!source) throw new Error("Pass the path to GeoNames AU.txt");

const seen = new Set();
const lines = [];
for (const row of readFileSync(source, "utf8").split("\n")) {
  const [, postcode, name, , state, , , , , lat, lon, accuracy] = row.split("\t");
  if (accuracy?.trim() !== PRECISE || !name || !lat || !lon) continue;
  const key = `${name}|${state}`;
  if (seen.has(key)) continue;
  seen.add(key);
  lines.push(`${name}|${state}|${postcode}|${Number(lat).toFixed(3)}|${Number(lon).toFixed(3)}`);
}

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../web/api/_lib/auSuburbs.js");
writeFileSync(
  out,
  `// Generated by scripts/make-au-suburbs.mjs. Do not edit by hand.
// Australian suburbs from GeoNames (https://www.geonames.org), CC BY 4.0.
// Each line: name|state|postcode|latitude|longitude
export const AU_SUBURBS = \`${lines.join("\n")}\`;
`
);
console.log(`Wrote ${lines.length} suburbs to ${out}`);
